import json

from week2.day3.main import extend_vocab, init_vocab
from week2.day4.main import encode_bpe
from week2.day5.main import load_tokenizer, save_tokenizer, decode_bpe


def train_tokenizer(text, size, path):
    if size < 257:
        raise ValueError('Vocabulary must contain 256 bytes and an EOD token')
    vocab = init_vocab()
    _, merges = extend_vocab(text, size - 1, vocab)
    eod = len(vocab)
    vocab[eod] = b''
    save_tokenizer(path, vocab, merges)
    artifact = json.loads(path.read_text())
    artifact.update(version=1, special_tokens={'<|endoftext|>': eod},
                    training={'requested_vocab_size': size, 'algorithm': 'week2/day3'})
    path.write_text(json.dumps(artifact), encoding='utf-8')
    return vocab, merges, eod


def read_tokenizer(path):
    vocab, merges = load_tokenizer(path)
    artifact = json.loads(path.read_text())
    eod = artifact.get('special_tokens', {}).get('<|endoftext|>')
    if set(vocab) != set(range(len(vocab))):
        raise ValueError('Tokenizer IDs must be contiguous')
    return vocab, merges, eod


def decode_generated(ids, vocab, eod):
    # Generated byte sequences can end inside a UTF-8 character.
    return b''.join(vocab[i] for i in ids if i != eod).decode('utf-8', errors='replace')
